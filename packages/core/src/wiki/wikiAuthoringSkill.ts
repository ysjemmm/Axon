import type { LoadedSkill } from "../skills/skillLoader.js";

const BODY = `# 项目 Wiki 撰写

你的任务是为一个代码仓库沉淀**结构化知识文档**。读者是未来的同事和你自己：
他们要能靠这些文档快速回答"这块是怎么实现的""改这里会影响什么""本项目有什么约定"，
而不必把代码通读一遍。

## 铁律：sources 必须真实

每页都要声明它依据了哪些文件（相对工作区根的路径）。这是**过时检测的唯一依据** ——
系统靠比对源文件的修改时间判断页面是否已失真。

- 只写**你确实读过**的文件，不要凭印象、凭目录名猜测
- 填写错了会导致最糟的结果：页面已经失真、系统却认为它新鲜，读者被误导。
  **一份错误的文档比没有文档更糟** —— 没有时人会去读代码，有了就信了。

## 规划阶段（若任务要求你产出页面清单）

先用工具把仓库摸清楚，再决定页面划分：

1. \`list_dir\` 看顶层结构；读 README / package.json / 构建配置，弄清这是什么项目
2. 找出**主干**：入口文件、核心模块、主要数据流经过的地方
3. 决定页面划分。粒度取「一个模块 / 一个关注点」：
   - 太粗（如"整个项目"）：任何局部改动都会让整页失效，增量维护无从谈起
   - 太细（一个函数一页）：页数膨胀，注入模型的索引变长，反而没人看
   - 合适的样子：「订单系统」「鉴权流程」「构建与发布」「数据库模型」「错误处理约定」
4. 每页在计划里给出：title、summary（一句话，会进注入模型的索引，务必短）、
   你打算依据的 sources（此后撰写时要真的去读）
5. 用 \`wiki_plan_pages\` 提交计划。**一次性提交完整清单**，不要分批。

一般 5~15 页。项目小就少几页，不要为凑数而写。

## 撰写阶段（若任务给定了一个具体页面）

只聚焦这一页，不要顺手写别的：

1. 读该页的 sources —— 完整读，理解实现而不是扫一眼签名
2. 必要时扩展阅读：调用方、被调用方、类型定义、相关测试。代码里读不出"为什么"时，
   去翻 git 历史或相关文档
3. 按下面的取舍撰写正文

### 该写什么
- **架构与职责**：这个模块边界在哪、负责什么、不负责什么
- **关键数据流**：一件事从进入到产出的完整路径，经过哪些环节
- **外部依赖与集成点**：和谁交互、契约是什么
- **非显而易见的约定与坑**：为什么这么设计、踩过什么、什么改动会连带影响哪里

### 不该写什么
- 这次改了什么、待办清单、进度 —— 那是任务记录，不是知识
- "本文件定义了一个类" 这种看代码就知道的复述
- 与代码无关的笔记、猜测、不确定的判断（不确定就写"未确认"，别编）

### 写法
- Markdown，中文。多用小标题，让人能跳读
- 讲实现时**带上文件路径**，读者能直接跳过去
- 结论先行：先说这块是干什么的，再展开细节
- 不要复制大段源码。引用关键片段即可，重点是解释而不是摘抄

## 完成后

用 \`wiki_save_page\` 提交。工具会立即落盘，不需要再确认。
写入前自查一遍：sources 是否都是真实读过的？正文里的人名/路径/结论是否都能在代码中找到依据？`;

